// detectorKind says how a detector's matches are replaced.
type detectorKind uint8

const (
	kindMarker detectorKind = iota // the match is replaced by a marker
	kindValue                      // only a value after a key or scheme; exempt from the UUID exclusion
	kindIP                         // public-ip: replaced by its truncated network (R34)
)

// classSet is a bit set of the classes a detector applies to.
type classSet uint16

func classSetOf(cs ...Class) classSet {
	var s classSet
	for _, c := range cs {
		s |= 1 << c
	}
	return s
}

func (s classSet) has(c Class) bool { return s&(1<<c) != 0 }

// "Applies to" of §4.2.
var (
	allClasses  = classSetOf(TName, TPath, TText, EText, LValue, NPatterned)
	textClasses = classSetOf(TText, EText)
)

// span is one match over normalised text, as byte offsets. repl is used
// only by kindIP.
type span struct {
	start, end int
	repl       string
}

// detector is one row of the §4.2 rule table.
type detector struct {
	id      string
	kind    detectorKind
	extend  bool
	numeric bool // a number detector: kept inside digests and container IDs (R33)
	classes classSet
	find    func(s string) ([]span, error)
	// samples returns the built-in positive and negative self-test inputs
	// (R42), built at run time from fragments.
	samples func() (pos, neg []string)
	// res is every compiled expression find runs, and tables the names
	// and parameters of its validators and the tables they read. The
	// rule-set digest hashes these, never a description written beside
	// them (§4.5, S5).
	res    []*regexp.Regexp
	tables []string
}

// hooks are test seams; nil in production.
var hooks struct {
	detect    func(id string, n int) // before each detector call, with its input length
	b64       func(n int)            // characters handed to the bounded base64 decoder
	normalise func(c Class, n int)   // before normalisation, with the input length
	work      func(n int)            // bytes a detector's scanning step examined
}

// work reports n bytes examined to the test hook, so tests can check that
// detection is linear without a wall clock.
func work(n int) {
	if hooks.work != nil {
		hooks.work(n)
	}
}

// ruleTable compiles the §4.2 table once. The patterns are constants; a
// pattern that does not compile panics here, and New turns that panic into
// ErrRulesUnavailable (R42).
var ruleTable = sync.OnceValue(func() []detector {
	return []detector{
		pemPrivateKey(),
		pemBodyLine(),
		pemPrivateKeyB64(),
		wardenEnrollmentToken(),
		awsAccessKeyID(),
		awsSecretKey(),
		vendorToken(),
		jwtToken(),
		urlCredentials(),
		urlSecretParam(),
		authorizationHeader(),
		cookieHeader(),
		secretAssignment(),
		email(),
		phone(),
		nationalIDJO(),
		nationalIDSA(),
		nationalIDAE(),
		paymentCard(),
		iban(),
		publicIP(),
	}
})

func defaultRules() []detector { return append([]detector(nil), ruleTable()...) }

// Detectors returns the detector IDs in §4.2 order.
func Detectors() (ids []string) {
	defer func() {
		if recover() != nil {
			ids = nil
		}
	}()
	for _, d := range ruleTable() {
		ids = append(ids, d.id)
	}
	return ids
}

// RulesDigest is the SHA-256 of the canonical rule table (§4.5): every
// detector's ID, flags, the source of every compiled pattern it runs and
// its validators in §4.2 order, the validator and normalisation tables,
// the limits and the version. It is a build-time constant
// (rules_digest.go, regenerated by go generate and checked for drift by a
// test), so the package computes no hash other than the pseudonyms (R12).
func RulesDigest() (sum [32]byte) {
	b, err := hex.DecodeString(rulesDigestHex)
	if err != nil || len(b) != len(sum) {
		return sum
	}
	copy(sum[:], b)
	return sum
}

